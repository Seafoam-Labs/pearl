#!/usr/bin/env python3
"""Browser validation for the offline Plugins mockup; no native runtime access."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parent
checks, errors = [], []
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
    page = browser.new_page(viewport={'width':1440, 'height':1150}, device_scale_factor=1)
    page.on('pageerror', lambda error: errors.append(str(error)))
    def visit(query=''):
        page.goto((ROOT/'index.html').as_uri()+query)
    def shot(name):
        page.screenshot(path=str(ROOT/(name+'.png')), full_page=True)
    def check(name, condition):
        assert condition, name
        checks.append(name)
    def expand(plugin):
        page.locator(f'[data-details="{plugin}"] > summary').click()
    visit()
    check('four-real-example-packages', page.locator('.plugin-card').count()==4)
    check('initial-approval-gate', page.locator('[data-id="zig"][data-toggle="enabled"]').is_disabled())
    shot('desktop')
    page.locator('[data-review="zig"]').first.click()
    shot('review')
    page.keyboard.press('Escape')
    check('escape-closes-review-and-restores-focus', page.locator('#review-dialog').is_hidden() and page.locator('[data-review="zig"]').first.evaluate('(e)=>e===document.activeElement'))
    page.locator('[data-review="zig"]').first.click()
    page.locator('#review-form button[type="submit"]').click()
    check('approval-is-staged', page.locator('#apply').is_enabled() and 'Review needed' in page.locator('#card-zig').inner_text())
    page.locator('[data-id="zig"][data-toggle="enabled"]').click()
    page.locator('#apply').click()
    check('apply-approval-and-enablement', 'Running' in page.locator('#card-zig').inner_text() and page.locator('#apply').is_disabled())
    page.locator('[data-id="cat"][data-toggle="enabled"]').click()
    check('enablement-does-not-change-live-status-before-apply', 'Running' in page.locator('#card-cat').inner_text())
    page.locator('#discard').click()
    check('discard-restores-enabled-state', page.locator('[data-id="cat"][data-toggle="enabled"]').get_attribute('aria-checked')=='true')
    expand('cat')
    page.locator('[data-toggle="overlay"]').click()
    check('revoking-overlay-returns-to-bar', page.locator('[data-field="mode"]').input_value()=='bar')
    page.locator('[data-field="mode"]').select_option('overlay')
    check('selecting-overlay-grants-permission', page.locator('[data-toggle="overlay"]').get_attribute('aria-checked')=='true')
    page.locator('[data-field="width"]').fill('200')
    page.locator('#apply').click()
    page.locator('[data-details="cat"] > summary').scroll_into_view_if_needed()
    shot('details')
    page.locator('[data-preview="cat"]').click()
    check('synthetic-preview-opens', page.locator('#preview-dialog').is_visible())
    page.keyboard.press('Escape')
    check('preview-restores-focus', page.locator('[data-preview="cat"]').evaluate('(e)=>e===document.activeElement'))
    visit()
    expand('timer')
    page.locator('[data-field="seconds"]').fill('90')
    page.locator('[data-preview="timer"]').click()
    check('preview-uses-saved-settings', '01:00' in page.locator('#preview-scene').inner_text())
    page.keyboard.press('Escape')
    page.locator('#refresh').click()
    page.wait_for_function("!document.querySelector('#refresh').disabled")
    check('refresh-preserves-draft', page.locator('[data-field="seconds"]').input_value()=='90' and page.locator('#apply').is_enabled())
    page.locator('[data-field="seconds"]').fill('0')
    page.locator('#search').fill('Cat')
    page.locator('#apply').click()
    check('invalid-hidden-setting-blocks-apply-and-reveals-field', page.locator('[data-field="seconds"]').is_visible() and page.locator('#apply').is_enabled())
    page.locator('[data-field="seconds"]').fill('')
    page.locator('#apply').click()
    check('empty-numeric-value-rejected', page.locator('#apply').is_enabled())
    page.locator('[data-field="seconds"]').fill('125')
    page.locator('#apply').click()
    page.locator('[data-reset="timer"]').click()
    check('reset-settings-stages-default', page.locator('[data-field="seconds"]').input_value()=='60' and page.locator('#apply').is_enabled())
    page.locator('#discard').click()
    check('discard-restores-saved-number', page.locator('[data-field="seconds"]').input_value()=='125')
    page.locator('[data-id="timer"][data-toggle="enabled"]').click()
    page.locator('[data-retry="rust"]').first.click()
    page.locator('#discard').click()
    check('retry-immediate-and-not-reverted-by-discard', 'Running' in page.locator('#card-rust').inner_text())
    page.locator('#search').fill('no such plugin')
    check('search-empty-state', 'No matching plugins' in page.locator('#plugins').inner_text())
    page.locator('#clear-search').click()
    check('clear-filters-restores-list', page.locator('.plugin-card').count()==4)
    page.locator('#filter').select_option('attention')
    check('attention-filter', page.locator('.plugin-card').count()==1)
    visit('?state=changed')
    page.locator('[data-review="cat"]').first.click()
    check('changed-package-requires-fresh-optional-grants', not page.locator('#grant-activity').is_checked() and not page.locator('#grant-overlay').is_checked())
    page.keyboard.press('Escape')
    shot('changed')
    visit('?state=missing')
    page.locator('[data-id="cat"][data-toggle="enabled"]').click()
    page.locator('#apply').click()
    check('missing-package-can-be-disabled', page.locator('[data-id="cat"][data-toggle="enabled"]').get_attribute('aria-checked')=='false')
    visit('?state=unavailable&view=details')
    check('unavailable-runtime-disables-live-actions', page.locator('[data-preview="cat"]').is_disabled() and page.locator('[data-retry="cat"]').is_disabled())
    visit('?state=empty')
    check('empty-inventory-has-install-guidance', 'A little extra starts here' in page.locator('#plugins').inner_text())
    visit('?theme=light')
    shot('light')
    for width in (560,390):
        page.set_viewport_size({'width':width,'height':1000})
        visit()
        check(f'no-horizontal-overflow-{width}', page.evaluate('document.documentElement.scrollWidth <= innerWidth'))
        shot('narrow' if width==560 else 'compact')
        page.locator('#sections').click()
        check(f'compact-navigation-{width}', page.locator('#navigation').is_visible())
        page.keyboard.press('Escape')
        check(f'compact-navigation-focus-{width}', page.locator('#sections').evaluate('(e)=>e===document.activeElement'))
        page.locator('[data-review="zig"]').first.click()
        check(f'review-fits-{width}', page.locator('#review-dialog').bounding_box()['width']<=width)
    page.set_viewport_size({'width':390,'height':600})
    check('short-dialog-actions-reachable', page.locator('#review-form button[type="submit"]').is_visible() and page.locator('#review-dialog').bounding_box()['height']<=580)
    shot('review-compact')
    check('no-javascript-runtime-errors', not errors)
    browser.close()
(ROOT/'verification.json').write_text(json.dumps({'status':'passed','scope':'Offline HTML mockup only; not native GTK or plugin runtime validation','checks':checks,'runtime_errors':errors}, indent=2)+'\n')
print(f'Passed {len(checks)} prototype checks')
