test "named GTK provider survives closing the last writer until all followers leave" {
    if (c.gtk_init_check() == 0) return error.SkipZigTest;
    var first: Appearance = .{
        .mode = .follow_pearl,
        .scope = "coral-window-1",
        .gtk_name = u.z("Adwaita"),
        .revision = 1,
        .snapshot_gtk = true,
        .context = undefined,
        .changed = undefined,
    };
    defer first.deinit();
    var second: Appearance = .{
        .mode = .follow_pearl,
        .scope = "coral-window-2",
        .gtk_name = u.z("Adwaita"),
        .variant = .light,
        .revision = 1,
        .snapshot_gtk = true,
        .context = undefined,
        .changed = undefined,
    };
    defer second.deinit();
    first.paint();
    second.paint();
    // Repainting a holder must not acquire another lease.
    second.paint();
    try std.testing.expectEqual(@as(usize, 2), NamedTheme.users);
    try std.testing.expect(first.native_provider != null);
    try std.testing.expectEqual(first.native_provider, second.native_provider);
    const provider = first.native_provider.?;
    const before = c.gtk_css_provider_to_string(provider);
    defer c.g_free(before);
    second.deinit();
    try std.testing.expectEqual(@as(usize, 1), NamedTheme.users);
    try std.testing.expectEqual(provider, NamedTheme.provider.?);
    const after = c.gtk_css_provider_to_string(provider);
    defer c.g_free(after);
    try std.testing.expectEqualStrings(std.mem.span(before), std.mem.span(after));
    // A surviving follower switching to custom mode releases the final lease.
    first.snapshot_gtk = false;
    first.paint();
    try std.testing.expect(first.native_provider == null);
    try std.testing.expectEqual(@as(usize, 0), NamedTheme.users);
    try std.testing.expect(NamedTheme.provider == null and NamedTheme.display == null);
    first.snapshot_gtk = true;
    first.paint();
    try std.testing.expectEqual(@as(usize, 1), NamedTheme.users);
    first.deinit();
    try std.testing.expectEqual(@as(usize, 0), NamedTheme.users);
    try std.testing.expect(NamedTheme.provider == null and NamedTheme.display == null);
}

