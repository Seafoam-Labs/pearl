    self.revision = 1;
    self.palette.primary = "bad";
    try std.testing.expectError(error.InvalidPalette, self.sheet(a));
}

// Check every selector, including comma-separated alternatives, rather than
// just the first rule: a single unscoped child rule can leak to another window.
fn expectScopedSheet(css: []const u8, scope: []const u8) !void {
    const prefix = try std.fmt.allocPrint(std.testing.allocator, ".coral.{s}", .{scope});
    defer std.testing.allocator.free(prefix);
    var rules = std.mem.splitScalar(u8, css, '}');
    var count: usize = 0;
    while (rules.next()) |rule| {
        var trimmed = std.mem.trim(u8, rule, " \n\r\t");
        while (std.mem.startsWith(u8, trimmed, "/*")) {
            const end = std.mem.indexOf(u8, trimmed, "*/") orelse return error.UnclosedComment;
            trimmed = std.mem.trimStart(u8, trimmed[end + 2 ..], " \n\r\t");
        }
        if (trimmed.len == 0) continue;
        const brace = std.mem.indexOfScalar(u8, trimmed, '{') orelse return error.MissingRule;
        var selectors = std.mem.splitScalar(u8, trimmed[0..brace], ',');
        while (selectors.next()) |raw| {
            var selector = std.mem.trim(u8, raw, " \n\r\t");
            if (std.mem.startsWith(u8, selector, "window")) selector = selector["window".len..];
            try std.testing.expect(std.mem.startsWith(u8, selector, prefix));
            try std.testing.expect(selector.len == prefix.len or selector[prefix.len] == ' ');
            count += 1;
        }
    }
    try std.testing.expect(count > 0);
    try std.testing.expect(std.mem.indexOf(u8, css, "$scope") == null);
}

test "window scope isolates all selectors without changing mode classes" {
    const a = std.testing.allocator;
    var self: Appearance = .{ .scope = "coral-window-17", .context = undefined, .changed = undefined };
    for ([_]?Mode{ null, .dark, .light, .follow_pearl }) |mode| {
        self.mode = mode;
        const css = try self.sheet(a);
        defer a.free(css);
        try expectScopedSheet(css, self.scope);
        try std.testing.expectEqualStrings(if (mode == .light) "light" else "dark", self.themeClass());
        try std.testing.expectEqualStrings(self.scope, self.cssScope());
    }
    self.mode = .follow_pearl;
    self.revision = 1;
    self.variant = .light;
    self.palette = client.theme.light;
    self.reduced_motion = true;
    const css = try self.sheet(a);
    defer a.free(css);
    try expectScopedSheet(css, self.scope);
    try std.testing.expectEqualStrings("light", self.themeClass());
    try std.testing.expect(std.mem.indexOf(u8, css, ".coral.coral-window-17 { font-family: \"Sans\"; font-size: 14pt; }") != null);
    try std.testing.expect(std.mem.indexOf(u8, css, ".coral.coral-window-17 * { transition-duration: 0ms; animation-duration: 0ms; }") != null);
}

