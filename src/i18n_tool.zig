//! AST-based extraction. Never changes application code or translator-owned PO files.
const std = @import("std");
const A = std.mem.Allocator;
const Ast = std.zig.Ast;
const Message = struct { domain: []const u8, source: []const u8, translated: []const u8, reference: []const u8, context: ?[]const u8 = null, plural: ?[]const u8 = null, comment: []const u8 = "" };
const Tool = struct {
    a: A,
    io: std.Io,
    messages: std.ArrayList(Message) = .empty,
    check: bool = false,
    fn write(self: *Tool, path: []const u8, bytes: []const u8) !void {
        if (self.check) {
            const old = try std.Io.Dir.cwd().readFileAlloc(self.io, path, self.a, .limited(8 * 1024 * 1024));
            if (!std.mem.eql(u8, old, bytes)) {
                std.debug.print("Stale generated file: {s}\n", .{path});
                return error.StaleTemplate;
            }
        } else try std.Io.Dir.cwd().writeFile(self.io, .{ .sub_path = path, .data = bytes });
    }
    fn aqueous(self: *Tool) !void {
        const path = "tests/fixtures/aqueous-master/snapshot.json";
        const bytes = try std.Io.Dir.cwd().readFileAlloc(self.io, path, self.a, .limited(4 * 1024 * 1024));
        const data = try std.json.parseFromSliceLeaky(std.json.Value, self.a, bytes, .{});
        const fields = data.object.get("fields").?.array.items;
        var output: std.Io.Writer.Allocating = .init(self.a);
        try output.writer.writeAll("//! Generated by i18n_tool extract from the pinned Aqueous schema.\npub const Field = struct { id: []const u8, label: [:0]const u8, description: [:0]const u8, options: []const [:0]const u8 };\npub const fields = [_]Field{\n");
        for (fields) |field| {
            const id = field.object.get("id").?.string;
            const label = field.object.get("label").?.string;
            const description = if (field.object.get("description")) |v| if (v == .string) v.string else "" else "";
            try output.writer.writeAll(".{ .id = ");
            try quote(&output.writer, id);
            try output.writer.writeAll(", .label = ");
            try quote(&output.writer, label);
            try output.writer.writeAll(", .description = ");
            try quote(&output.writer, description);
            try output.writer.writeAll(", .options = &.{");
            if (field.object.get("options")) |values| if (values == .array) for (values.array.items) |value| {
                if (value != .string) continue;
                try quote(&output.writer, value.string);
                try output.writer.writeByte(',');
                try self.addFull(.{ .domain = "pearl", .source = value.string, .context = try std.fmt.allocPrint(self.a, "aqueous.{s}.option", .{id}), .translated = "", .reference = path, .comment = "Display label only; the underlying Aqueous option value is unchanged." });
            };
            try output.writer.writeAll("} },\n");
            try self.addFull(.{ .domain = "pearl", .source = label, .context = try std.fmt.allocPrint(self.a, "aqueous.{s}.label", .{id}), .translated = "", .reference = path });
            try self.addFull(.{ .domain = "pearl", .source = description, .context = try std.fmt.allocPrint(self.a, "aqueous.{s}.description", .{id}), .translated = "", .reference = path });
        }
        try output.writer.writeAll("};\n");
        const source = try self.a.dupeZ(u8, output.written());
        var tree = try Ast.parse(self.a, source, .zig);
        defer tree.deinit(self.a);
        try self.write("src/i18n/aqueous_fields.zig", try tree.renderAlloc(self.a));
    }
    fn formatTemplate(self: *Tool, value: []const u8) ![]const u8 {
        var out: std.Io.Writer.Allocating = .init(self.a);
        var pos: usize = 0;
        var index: usize = 0;
        while (pos < value.len) {
            if (value[pos] == '{' and pos + 1 < value.len and value[pos + 1] != '{') {
                const end = std.mem.indexOfScalarPos(u8, value, pos, '}') orelse return error.InvalidFormat;
                try out.writer.print("{{{d}}}", .{index});
                index += 1;
                pos = end + 1;
            } else {
                try out.writer.writeByte(value[pos]);
                if ((value[pos] == '{' or value[pos] == '}') and pos + 1 < value.len and value[pos + 1] == value[pos]) {
                    pos += 1;
                    try out.writer.writeByte(value[pos]);
                }
                pos += 1;
            }
        }
        return out.written();
    }
    fn gallery(self: *Tool) !void {
        const path = "src/ui/i18n.zig";
        const source = try std.Io.Dir.cwd().readFileAllocOptions(self.io, path, self.a, .limited(65536), .of(u8), 0);
        var tree = try Ast.parse(self.a, source, .zig);
        defer tree.deinit(self.a);
        var english: ?Ast.Node.Index = null;
        for (tree.rootDecls()) |decl| if (tree.fullVarDecl(decl)) |v| {
            const name = tree.tokenSlice(v.ast.mut_token + 1);
            if (std.mem.eql(u8, name, "en")) english = v.ast.init_node.unwrap();
        };
        var eb: [2]Ast.Node.Index = undefined;
        const en = tree.fullStructInit(&eb, english.?).?.ast.fields;
        for (en) |field| try self.add("pearl", (try self.literal(tree, field)).?, "", try std.fmt.allocPrint(self.a, "{s}:{d}", .{ path, std.mem.count(u8, source[0..tree.tokenStart(tree.firstToken(field))], "\n") + 1 }));
    }
    fn add(self: *Tool, domain: []const u8, source: []const u8, translated: []const u8, reference: []const u8) !void {
        try self.addFull(.{ .domain = domain, .source = source, .translated = translated, .reference = reference });
    }
    fn addFull(self: *Tool, message: Message) !void {
        const source = message.source;
        const domain = message.domain;
        const translated = message.translated;
        if (source.len == 0) return;
        for (self.messages.items) |*m| {
            if (!std.mem.eql(u8, m.domain, domain) or !std.mem.eql(u8, m.source, source) or !std.mem.eql(u8, m.context orelse "", message.context orelse "")) continue;
            if (!std.mem.eql(u8, m.plural orelse "", message.plural orelse "")) return error.ConflictingPlural;
            if (m.translated.len == 0 and translated.len > 0) m.translated = translated;
            if (std.mem.indexOf(u8, m.reference, message.reference) == null) m.reference = try std.fmt.allocPrint(self.a, "{s} {s}", .{ m.reference, message.reference });
            if (message.comment.len > 0 and std.mem.indexOf(u8, m.comment, message.comment) == null) m.comment = try std.fmt.allocPrint(self.a, "{s}{s}{s}", .{ m.comment, if (m.comment.len > 0) "\n" else "", message.comment });
            return;
        }
        try self.messages.append(self.a, message);
    }
    fn literal(self: *Tool, tree: Ast, node: Ast.Node.Index) !?[]const u8 {
        if (tree.nodeTag(node) == .string_literal) return try std.zig.string_literal.parseAlloc(self.a, tree.getNodeSource(node));
        if (tree.nodeTag(node) == .multiline_string_literal) {
            var output: std.Io.Writer.Allocating = .init(self.a);
            var lines = std.mem.splitScalar(u8, tree.getNodeSource(node), '\n');
            var first = true;
            while (lines.next()) |line| {
                const clean = std.mem.trimStart(u8, line, " \t");
                if (!std.mem.startsWith(u8, clean, "\\\\")) continue;
                if (!first) try output.writer.writeByte('\n');
                try output.writer.writeAll(clean[2..]);
                first = false;
            }
            return output.written();
        }
        return null;
    }
    fn file(self: *Tool, path: []const u8, domain: []const u8) !void {
        const source = try std.Io.Dir.cwd().readFileAllocOptions(self.io, path, self.a, .limited(4 * 1024 * 1024), .of(u8), 0);
        try self.extractSource(path, source, domain);
    }
    fn extractSource(self: *Tool, path: []const u8, bytes: [:0]const u8, _: []const u8) !void {
        var tree = try Ast.parse(self.a, bytes, .zig);
        defer tree.deinit(self.a);
        if (tree.errors.len > 0) return error.InvalidZig;
        for (0..tree.nodes.len) |index| {
            const node: Ast.Node.Index = @enumFromInt(index);
            var buf: [1]Ast.Node.Index = undefined;
            const call = tree.fullCall(&buf, node) orelse continue;
            const name = tree.getNodeSource(call.ast.fn_expr);
            const tail = name[(if (std.mem.lastIndexOfScalar(u8, name, '.')) |p| p + 1 else 0)..];
            if (!std.mem.eql(u8, name, "tr") and !std.mem.startsWith(u8, name, "i18n.") and !std.mem.startsWith(u8, name, "@import(\"i18n\").")) continue;
            const kind = std.meta.stringToEnum(enum { tr, dtr, mark, context, dcontext, ntr, dntr, message, dmessage, nmessage, dnmessage, fmt, fmtAlloc, dfmt, dfmtAlloc }, tail) orelse continue;
            const params = call.ast.params;
            const explicit_domain = switch (kind) {
                .dtr, .dcontext, .dntr, .dmessage, .dnmessage, .dfmt, .dfmtAlloc => true,
                else => false,
            };
            const offset: usize = @intFromBool(explicit_domain);
            const source_index: usize = offset + switch (kind) {
                .context, .dcontext, .message, .dmessage, .nmessage, .dnmessage, .fmt, .fmtAlloc, .dfmt, .dfmtAlloc => @as(usize, 1),
                else => 0,
            };
            if (params.len <= source_index) return error.InvalidTranslationCall;
            const original = try self.literal(tree, params[source_index]) orelse continue;
            const domain = if (explicit_domain) try self.literal(tree, params[0]) orelse return error.LiteralDomainRequired else "pearl";
            for ([_][]const u8{ "pearl", "pearl-greeter", "pearl-lock", "pearl-files", "pearl-agent", "phyto", "dome", "coral" }) |known| {
                if (std.mem.eql(u8, domain, known)) break;
            } else return error.UnknownDomain;
            const context = switch (kind) {
                .context, .dcontext => try self.literal(tree, params[offset]) orelse return error.LiteralContextRequired,
                else => null,
            };
            const plural = switch (kind) {
                .ntr, .dntr, .nmessage, .dnmessage => if (params.len > source_index + 1) try self.literal(tree, params[source_index + 1]) orelse return error.LiteralPluralRequired else return error.InvalidTranslationCall,
                else => null,
            };
            const start = tree.tokenStart(tree.firstToken(node));
            const line = std.mem.count(u8, bytes[0..start], "\n") + 1;
            var comment: []const u8 = "";
            var end = if (std.mem.lastIndexOfScalar(u8, bytes[0..start], '\n')) |p| p + 1 else 0;
            while (end > 0) {
                const begin = if (std.mem.lastIndexOfScalar(u8, bytes[0 .. end - 1], '\n')) |p| p + 1 else 0;
                const previous = std.mem.trim(u8, bytes[begin .. end - 1], " \t\r");
                const prefix = "// Translators:";
                if (!std.mem.startsWith(u8, previous, prefix)) break;
                comment = try std.fmt.allocPrint(self.a, "{s}{s}{s}", .{ std.mem.trimStart(u8, previous[prefix.len..], " "), if (comment.len > 0) "\n" else "", comment });
                end = begin;
            }
            try self.addFull(.{ .domain = domain, .source = switch (kind) {
                .fmt, .fmtAlloc, .dfmt, .dfmtAlloc => try self.formatTemplate(original),
                else => original,
            }, .context = context, .plural = plural, .translated = "", .reference = try std.fmt.allocPrint(self.a, "{s}:{d}", .{ path, line }), .comment = comment });
        }
    }
    fn scan(self: *Tool, root: []const u8, default_domain: []const u8) !void {
        var dir = try std.Io.Dir.cwd().openDir(self.io, root, .{ .iterate = true });
        defer dir.close(self.io);
        var walker = try dir.walk(self.a);
        defer walker.deinit();
        var paths: std.ArrayList([]const u8) = .empty;
        while (try walker.next(self.io)) |entry| {
            if (entry.kind != .file or !std.mem.endsWith(u8, entry.path, ".zig")) continue;
            if (std.mem.startsWith(u8, entry.path, "i18n/") or std.mem.eql(u8, entry.path, "i18n_tool.zig") or std.mem.eql(u8, entry.path, "i18n_probe.zig") or std.mem.eql(u8, entry.path, "ui/i18n.zig")) continue;
            try paths.append(self.a, try std.fs.path.join(self.a, &.{ root, entry.path }));
        }
        std.mem.sort([]const u8, paths.items, {}, struct {
            fn less(_: void, l: []const u8, r: []const u8) bool {
                return std.mem.lessThan(u8, l, r);
            }
        }.less);
        for (paths.items) |path| {
            const domain = if (std.mem.startsWith(u8, path, "src/greeter/")) "pearl-greeter" else if (std.mem.startsWith(u8, path, "src/lock/")) "pearl-lock" else if (std.mem.startsWith(u8, path, "src/files/") or std.mem.startsWith(u8, path, "src/capture/")) "pearl-files" else if (std.mem.startsWith(u8, path, "src/agent/")) "pearl-agent" else default_domain;
            try self.file(path, domain);
        }
    }
    fn po(self: *Tool, domain: []const u8) ![]const u8 {
        var output: std.Io.Writer.Allocating = .init(self.a);
        const w = &output.writer;
        try w.writeAll("# Pearl translation catalog\n# See translations/README.md for licensing and contribution requirements.\nmsgid \"\"\nmsgstr \"\"\n\"Project-Id-Version: Pearl 1\\n\"\n\"MIME-Version: 1.0\\n\"\n\"Content-Type: text/plain; charset=UTF-8\\n\"\n\"Content-Transfer-Encoding: 8bit\\n\"\n");
        for (self.messages.items) |m| {
            if (!std.mem.eql(u8, m.domain, domain)) continue;
            try w.print("\n#: {s}\n", .{m.reference});
            var lines = std.mem.splitScalar(u8, m.comment, '\n');
            while (lines.next()) |line| if (line.len > 0) try w.print("#. {s}\n", .{line});
            if (m.context) |ctx| {
                try w.writeAll("msgctxt ");
                try quote(w, ctx);
                try w.writeByte('\n');
            }
            try w.writeAll("msgid ");
            try quote(w, m.source);
            if (m.plural) |plural| {
                try w.writeAll("\nmsgid_plural ");
                try quote(w, plural);
                try w.writeAll("\nmsgstr[0] \"\"\nmsgstr[1] \"\"");
            } else {
                try w.writeAll("\nmsgstr ");
                try quote(w, "");
            }
            try w.writeByte('\n');
        }
        return output.written();
    }
};
fn quote(w: *std.Io.Writer, s: []const u8) !void {
    try w.writeByte('"');
    for (s) |c| switch (c) {
        '"' => try w.writeAll("\\\""),
        '\\' => try w.writeAll("\\\\"),
        '\n' => try w.writeAll("\\n"),
        '\r' => try w.writeAll("\\r"),
        '\t' => try w.writeAll("\\t"),
        else => try w.writeByte(c),
    };
    try w.writeByte('"');
}
pub fn main(init: std.process.Init) !void {
    const a = init.arena.allocator();
    const args = try init.minimal.args.toSlice(a);
    if (args.len != 2 or (!std.mem.eql(u8, args[1], "extract") and !std.mem.eql(u8, args[1], "check"))) return error.UsageExtractOrCheck;
    var tool: Tool = .{ .a = a, .io = init.io, .check = std.mem.eql(u8, args[1], "check") };
    try tool.gallery();
    try tool.aqueous();
    try tool.scan("src", "pearl");
    for ([_][]const u8{ "phyto", "dome", "coral" }) |name| try tool.scan(try std.fmt.allocPrint(a, "subprojects/{s}/src", .{name}), name);
    std.mem.sort(Message, tool.messages.items, {}, struct {
        fn less(_: void, l: Message, r: Message) bool {
            const order = std.mem.order(u8, l.domain, r.domain);
            if (order != .eq) return order == .lt;
            const s = std.mem.order(u8, l.source, r.source);
            return if (s != .eq) s == .lt else std.mem.lessThan(u8, l.context orelse "", r.context orelse "");
        }
    }.less);
    for ([_][]const u8{ "pearl", "pearl-greeter", "pearl-lock", "pearl-files", "pearl-agent", "phyto", "dome", "coral" }) |domain| {
        try tool.write(try std.fmt.allocPrint(a, "translations/{s}.pot", .{domain}), try tool.po(domain));
    }
    std.debug.print("{d} catalog messages\n", .{tool.messages.items.len});
}

test "extract domains contexts plurals comments escaping multiline strings and formatting" {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    var tool: Tool = .{ .a = arena.allocator(), .io = std.testing.io };
    try tool.extractSource("fixture.zig",
        \\const i18n = @import("i18n");
        \\pub fn sample() void {
        \\    // Translators: File count, including zero.
        \\    _ = i18n.dnmessage("pearl-files", &buffer, "{n} file", "{n} files", n, args);
        \\    _ = i18n.context("verb", "Open");
        \\    _ = i18n.fmt(&buffer, "{d} at {s} {{ok}}", args);
        \\    _ = i18n.mark("A \"quote\" and \u{e4}");
        \\    _ = i18n.tr(
        \\        \\First line
        \\        \\Second line
        \\    );
        \\}
    , "pearl");
    try std.testing.expectEqual(@as(usize, 5), tool.messages.items.len);
    const plural = tool.messages.items[0];
    try std.testing.expectEqualStrings("pearl-files", plural.domain);
    try std.testing.expectEqualStrings("{n} files", plural.plural.?);
    try std.testing.expectEqualStrings("File count, including zero.", plural.comment);
    try std.testing.expectEqualStrings("fixture.zig:4", plural.reference);
    try std.testing.expectEqualStrings("verb", tool.messages.items[1].context.?);
    try std.testing.expectEqualStrings("{0} at {1} {{ok}}", tool.messages.items[2].source);
    try std.testing.expectEqualStrings("A \"quote\" and ä", tool.messages.items[3].source);
    try std.testing.expectEqualStrings("First line\nSecond line", tool.messages.items[4].source);
    const output = try tool.po("pearl-files");
    try std.testing.expect(std.mem.indexOf(u8, output, "#. File count, including zero.") != null);
    try std.testing.expect(std.mem.indexOf(u8, output, "msgid_plural \"{n} files\"") != null);
}
